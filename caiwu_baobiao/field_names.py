# 同比字段后缀
YOY_SUFFIX = '_YOY'
YOY_LABEL = '同比增长率'


def rename_columns(df, sheet):
    """把 DataFrame 的英文字段名换成中文表头；未收录的字段保留英文原名。"""
    mapping = FIELD_NAMES.get(sheet, COMMON)
    renamed = []
    for col in df.columns:
        name = mapping.get(col)
        if name is None and col.endswith(YOY_SUFFIX):
            base = mapping.get(col[: -len(YOY_SUFFIX)])
            if base is not None:
                name = f'{base}{YOY_LABEL}'
        renamed.append(name if name is not None else col)
    return df.rename(columns=dict(zip(df.columns, renamed)))
